async function seedNoticias() {
    const result = { created: 0, skipped: 0 };
    for (const noticia of DEFAULT_NOTICIAS) {
        const [, created] = await models.Noticia.findOrCreate({
            where: { slug: slugify(noticia.title) },
            defaults: {
                title: noticia.title,
                slug: slugify(noticia.title),
                category: noticia.category,
                author: noticia.author,
                summary: noticia.summary,
                body: noticia.body,
                image_url: noticia.imageUrl,
                reading_time: noticia.readingTime,
                tags: noticia.tags,
                related_ids: noticia.relatedIds,
                published_at: new Date(noticia.publishedAt),
                status: 2,
            },
        });
        if (created) result.created += 1;
        else result.skipped += 1;
    }
    return result;
}

module.exports = seedNoticias;
